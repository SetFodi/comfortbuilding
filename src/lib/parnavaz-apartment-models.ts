import type { ApartmentModel, PlanPoint } from "./apartment-model";

/**
 * Traced from the plan portion of each supplied interior concept board.
 * These are visual layouts, not dimensioned construction drawings.
 *
 * Keeping the traces in source pixels makes them auditable against the boards.
 * The viewer receives normalized coordinates inside each plan-only crop.
 */
function trace(model: ApartmentModel): ApartmentModel {
  const [left, top, width, height] = model.source.crop;
  const point = ([x, y]: PlanPoint): PlanPoint => [
    (x - left) / width,
    (y - top) / height,
  ];

  return {
    ...model,
    footprint: model.footprint.map(point),
    walls: model.walls.map(([start, end]) => [point(start), point(end)]),
    furniture: model.furniture.map((item) => ({
      ...item,
      rect: [
        (item.rect[0] - left) / width,
        (item.rect[1] - top) / height,
        item.rect[2] / width,
        item.rect[3] / height,
      ],
    })),
    viewpoints: model.viewpoints.map((viewpoint) => ({
      ...viewpoint,
      position: point(viewpoint.position),
      target: point(viewpoint.target),
    })),
  };
}

